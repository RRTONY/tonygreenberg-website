// Helper functions
export function getProducersByTier(tier: Producer["tier"]) {
  return producers.filter(p => p.tier === tier);
}

export function getUnicorns() {
  return getProducersByTier("Unicorn");
}

export function getLegends() {
  return getProducersByTier("Legend");
}

export function getGateway() {
  return getProducersByTier("Gateway");
}

export function getCheapestBuyLink(producer: Producer): BuyLink | null {
  if (producer.buyLinks.length === 0) return null;
  return producer.buyLinks.reduce((min, link) => link.price < min.price ? link : min);
}

export function getProducerById(id: string): Producer | undefined {
  return producers.find(p => p.id === id);
}
